const exactCaseLookup = new Map<string, TranslationEntry>();
const exactLookup = new Map<string, TranslationEntry>();

for (const entry of entries) {
  exactCaseLookup.set(entry.en, entry);
  exactCaseLookup.set(entry.tr, entry);
  exactLookup.set(entry.en.toLocaleLowerCase("en-US"), entry);
  exactLookup.set(entry.en.toLocaleLowerCase("tr-TR"), entry);
  exactLookup.set(entry.tr.toLocaleLowerCase("en-US"), entry);
  exactLookup.set(entry.tr.toLocaleLowerCase("tr-TR"), entry);
}

const phraseEntries = [...entries]
  .filter((entry) => entry.en.length >= 8 || entry.tr.length >= 8)
  .sort((a, b) => Math.max(b.en.length, b.tr.length) - Math.max(a.en.length, a.tr.length));

function preserveWhitespace(source: string, translated: string): string {
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

export function translateUiText(source: string, locale: AppLocale): string {
  const trimmed = source.trim();

  if (!trimmed) return source;

  const exact =
    exactCaseLookup.get(trimmed) ??
    exactLookup.get(trimmed.toLocaleLowerCase("en-US")) ??
    exactLookup.get(trimmed.toLocaleLowerCase("tr-TR"));
  if (exact) return preserveWhitespace(source, exact[locale]);

  let translated = trimmed;

  for (const entry of phraseEntries) {
    const from = locale === "tr" ? entry.en : entry.tr;
    const to = entry[locale];

    if (translated.includes(from)) {
      translated = translated.split(from).join(to);
    }
  }

  if (locale === "tr") {
    translated = translated
      .replace(/^(\d+) matches loaded$/i, "$1 maç yüklendi")
      .replace(/^(\d+) matches$/i, "$1 maç")
      .replace(/^(\d+) picks$/i, "$1 tahmin")
      .replace(/^(\d+) settled decisions$/i, "$1 sonuçlanmış karar")
      .replace(/^(\d+) settled picks$/i, "$1 sonuçlanmış tahmin")
      .replace(/^(\d+) archived picks$/i, "$1 arşivlenmiş tahmin")
      .replace(/^(\d+) won \/ (\d+) lost$/i, "$1 kazandı / $2 kaybetti")
      .replace(/^Average fair odds (.+)$/i, "Ortalama adil oran $1")
      .replace(/^Hello (.+)\. Only today's published selections are shown\.$/i, "Merhaba $1. Yalnız bugünün yayımlanmış seçimleri gösteriliyor.")
      .replace(/^Merhaba (.+)\. Yalnız bugünün yayınlanmış seçimleri gösteriliyor\.$/i, "Merhaba $1. Yalnız bugünün yayımlanmış seçimleri gösteriliyor.")
      .replace(/^(\d+) results?$/i, "$1 sonuç")
      .replace(/^(\d+) active requests?$/i, "$1 aktif talep")
      .replace(/^(\d+) registered members?$/i, "$1 kayıtlı üye")
      .replace(/^(\d+) records?$/i, "$1 kayıt")
      .replace(/^(\d+) active alerts?$/i, "$1 aktif uyarı")
      .replace(/^Probability: %([\d.]+) · Score: (.+)$/i, "Olasılık: %$1 · Skor: $2")
      .replace(/^(.+) membership$/i, "$1 üyelik")
      .replace(/^Final Score:\s*/i, "Maç Sonucu: ")
      .replace(/^Top Pick:\s*/i, "En İyi Tahmin: ")
      .replace(/^Top Pick Confidence:\s*/i, "En İyi Tahmin Güveni: ");
  } else {
    translated = translated
      .replace(/^(\d+) maç yüklendi$/i, "$1 matches loaded")
      .replace(/^(\d+) maç$/i, "$1 matches")
      .replace(/^(\d+) tahmin$/i, "$1 picks")
      .replace(/^(\d+) sonuçlanmış karar$/i, "$1 settled decisions")
      .replace(/^(\d+) sonuçlanmış tahmin$/i, "$1 settled picks")
      .replace(/^(\d+) arşivlenmiş tahmin$/i, "$1 archived picks")
      .replace(/^(\d+) kazandı \/ (\d+) kaybetti$/i, "$1 won / $2 lost")
      .replace(/^Ortalama adil oran (.+)$/i, "Average fair odds $1")
      .replace(/^Merhaba (.+)\. Yalnız bugünün (?:yayınlanmış|yayımlanmış) seçimleri gösteriliyor\.$/i, "Hello $1. Only today's published selections are shown.")
      .replace(/^Merhaba (.+)$/i, "Hello $1")
      .replace(/^(\d+) karşılaşma$/i, "$1 matches")
      .replace(/^(\d+) pazar$/i, "$1 markets")
      .replace(/^(\d+) cevap bekliyor$/i, "$1 waiting for reply")
      .replace(/^(Temel|Analiz|Profesyonel) üyelik kapsamı$/i, "$1 membership coverage")
      .replace(/^(\d+) sonuç$/i, "$1 results")
      .replace(/^(\d+) aktif talep$/i, "$1 active requests")
      .replace(/^(\d+) kayıtlı üye$/i, "$1 registered members")
      .replace(/^(\d+) kayıt$/i, "$1 records")
      .replace(/^(\d+) aktif uyarı$/i, "$1 active alerts")
      .replace(/^Olasılık: %([\d.]+) · Skor: (.+)$/i, "Probability: $1% · Score: $2")
      .replace(/^(.+) üyelik$/i, "$1 membership")
      .replace(/^Maç Sonucu:\s*/i, "Final Score: ")
      .replace(/^En İyi Tahmin:\s*/i, "Top Pick: ")
      .replace(/^En İyi Tahmin Güveni:\s*/i, "Top Pick Confidence: ");
  }

  if (locale === "tr") {
    translated = translated
      .replace(/^(\d+) primary HOME candidates$/i, "$1 ana ev sahibi adayı")
      .replace(/^(\d+) very high$/i, "$1 çok yüksek")
      .replace(/^(\d+) picks$/i, "$1 tahmin")
      .replace(/^(\d+) settled · (\d+) void$/i, "$1 sonuçlandı · $2 geçersiz")
      .replace(/^(\d+) players?$/i, "$1 oyuncu")
      .replace(/^(\d+) teams? stored in the database\.$/i, "$1 takım veritabanında kayıtlı.")
      .replace(/^(\d+) matches displayed$/i, "$1 maç gösteriliyor")
      .replace(/^(\d{4}) active player squad$/i, "$1 aktif oyuncu kadrosu")
      .replace(/^(.+) player photo$/i, "$1 oyuncu fotoğrafı");

    translated = translated
      .replace(/^(.+) to win$/i, "$1 kazanır")
      .replace(
        /^The teams are closely matched in (.+)\.$/i,
        (_match, label: string) =>
          `Takımlar ${translateUiText(label, "tr").toLocaleLowerCase("tr-TR")} açısından birbirine yakın.`,
      )
      .replace(
        /^(.+) is stronger than (.+) in (.+)\.$/i,
        (_match, stronger: string, weaker: string, label: string) =>
          `${stronger}, ${translateUiText(label, "tr").toLocaleLowerCase("tr-TR")} açısından ${weaker} takımından daha güçlü.`,
      )
      .replace(
        /^(.+) • (.+) has a model probability of ([\d.]+)% and reliability ([\d.]+)\/100\.$/i,
        "$1 • $2 için model olasılığı %$3, güvenilirlik puanı $4/100.",
      )
      .replace(
        /^The strongest market signal for this match is (.+) • (.+)\. Model probability is ([\d.]+)% and historical reliability is ([\d.]+)\/100\.$/i,
        "Bu maçın en güçlü bahis sinyali $1 • $2. Model olasılığı %$3, geçmiş güvenilirlik puanı $4/100.",
      )
      .replace(
        /^No (?:Top Pick|En İyi Tahmin) met the quality threshold for (.+) vs (.+)\.$/i,
        "$1 – $2 maçı için kalite eşiğini geçen güçlü tahmin bulunamadı.",
      );
  } else {
    translated = translated
      .replace(/^(\d+) ana ev sahibi adayı$/i, "$1 primary HOME candidates")
      .replace(/^(\d+) çok yüksek$/i, "$1 very high")
      .replace(/^(\d+) tahmin$/i, "$1 picks")
      .replace(/^(\d+) sonuçlandı · (\d+) geçersiz$/i, "$1 settled · $2 void")
      .replace(/^(\d+) oyuncu$/i, "$1 players")
      .replace(/^(\d+) takım veritabanında kayıtlı\.$/i, "$1 teams stored in the database.")
      .replace(/^(\d+) maç gösteriliyor$/i, "$1 matches displayed")
      .replace(/^(\d{4}) aktif oyuncu kadrosu$/i, "$1 active player squad")
      .replace(/^(.+) oyuncu fotoğrafı$/i, "$1 player photo")
      .replace(/^(.+) fotoğrafı$/i, "$1 player photo");

    translated = translated
      .replace(/^(.+) kazanır$/i, "$1 to win")
      .replace(
        /^(?:Takımlar|Teams) (.+) açısından birbirine yakın\.$/i,
        (_match, label: string) =>
          `The teams are closely matched in ${translateUiText(label, "en").toLocaleLowerCase("en-US")}.`,
      )
      .replace(
        /^(.+), (.+) açısından (.+) takımından daha güçlü\.$/i,
        (_match, stronger: string, label: string, weaker: string) =>
          `${stronger} is stronger than ${weaker} in ${translateUiText(label, "en").toLocaleLowerCase("en-US")}.`,
      )
      .replace(
        /^(.+) • (.+) için model olasılığı %([\d.]+), güvenilirlik puanı ([\d.]+)\/100\.$/i,
        "$1 • $2 has a model probability of $3% and reliability $4/100.",
      )
      .replace(
        /^Bu maçın en güçlü bahis sinyali (.+) • (.+)\. Model olasılığı %([\d.]+), geçmiş güvenilirlik puanı ([\d.]+)\/100\.$/i,
        "The strongest market signal for this match is $1 • $2. Model probability is $3% and historical reliability is $4/100.",
      )
      .replace(
        /^(.+) – (.+) maçı için kalite eşiğini geçen güçlü tahmin bulunamadı\.$/i,
        "No Top Pick met the quality threshold for $1 vs $2.",
      );
  }

  return preserveWhitespace(source, translated);
}
